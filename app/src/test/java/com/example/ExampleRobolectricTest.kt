package com.example

import android.content.Context
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import com.example.data.local.SonBarkaDatabase
import com.example.data.local.entity.DialectPreferenceEntity
import com.example.data.local.entity.StoryDraftEntity
import com.example.data.repository.StoryDraftRepository
import com.example.model.CulturalDialect
import com.example.model.Language
import com.example.model.NarrationDeliveryStyle
import com.example.service.CulturalContentCatalog
import com.example.service.GeminiVisualService
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class ExampleRobolectricTest {

  private lateinit var db: SonBarkaDatabase
  private lateinit var repository: StoryDraftRepository

  @Before
  fun setup() {
    val context = ApplicationProvider.getApplicationContext<Context>()
    db = Room.inMemoryDatabaseBuilder(context, SonBarkaDatabase::class.java)
      .allowMainThreadQueries()
      .build()
    repository = StoryDraftRepository(db.storyDraftDao(), db.dialectPreferenceDao())
  }

  @After
  fun tearDown() {
    db.close()
  }

  @Test
  fun testAppNameString() {
    val context = ApplicationProvider.getApplicationContext<Context>()
    val appName = context.getString(R.string.app_name)
    assertEquals("SON BARKA AI", appName)
  }

  @Test
  fun testRoomDatabaseSaveAndRetrieveStoryDraft() = runBlocking {
    val kanoDialect = CulturalContentCatalog.getDialectById("hausa_kananci")
    val draftId = repository.saveDraft(
      title = "Tatsuniyar Gizo",
      content = "Ga ta ga ta nan. Ta zo mu ji ta. Gizo ne da Koki suka je gona...",
      dialect = kanoDialect,
      deliveryStyle = NarrationDeliveryStyle.ELDER_GRIOT
    )

    assertTrue("Draft ID should be generated by Room", draftId > 0)

    val drafts = repository.allDrafts.first()
    assertEquals(1, drafts.size)
    assertEquals("Tatsuniyar Gizo", drafts[0].title)
    assertEquals(kanoDialect.id, drafts[0].dialectId)
    assertEquals(kanoDialect.name, drafts[0].dialectName)
    assertEquals("HAUSA", drafts[0].languageCode)
  }

  @Test
  fun testRoomDatabaseSaveAndRetrieveDialectPreference() = runBlocking {
    val fulfuldeDialect = CulturalContentCatalog.getDialectById("fulfulde_adamawa")
    repository.saveDialectPreference(
      dialect = fulfuldeDialect,
      deliveryStyle = NarrationDeliveryStyle.PASTORAL_POETIC
    )

    val preference = repository.getDialectPreferenceOnce()
    assertNotNull("Preference should be saved in Room", preference)
    assertEquals(fulfuldeDialect.id, preference?.dialectId)
    assertEquals(fulfuldeDialect.name, preference?.dialectName)
    assertEquals("FULFULDE", preference?.languageCode)
    assertEquals("PASTORAL_POETIC", preference?.deliveryStyleId)
  }

  @Test
  fun testCulturalContentCatalogHasHausaAndFulfulde() {
    val dialects = CulturalContentCatalog.CULTURAL_DIALECTS
    assertTrue("Should have multiple authentic dialects", dialects.size >= 8)

    val hausaDialects = CulturalContentCatalog.getDialectsForLanguage(Language.HAUSA)
    assertTrue("Should contain Hausa dialects", hausaDialects.isNotEmpty())

    val fulfuldeDialects = CulturalContentCatalog.getDialectsForLanguage(Language.FULFULDE)
    assertTrue("Should contain Fulfulde dialects", fulfuldeDialects.isNotEmpty())
  }

  @Test
  fun testGeminiCinematicVisualFallback() = runBlocking {
    val project = GeminiVisualService.generateCinematicVisuals(
      narrativeText = "Sarauniya Amina cavalry ride at sunset",
      cinematicStyle = "Sahelian Epic Cinema",
      aspectRatio = "16:9",
      cameraLens = "35mm Anamorphic"
    )

    assertNotNull("Visual project should be generated", project)
    assertTrue("Should generate connected scenes", project.scenes.isNotEmpty())
    assertTrue("Should retain character continuity", project.characterContinuityNotes.isNotBlank())
  }
}
